import assert from "node:assert/strict";
import test from "node:test";
import { readFile, writeFile, rm } from "node:fs/promises";
import { randomUUID } from "node:crypto";
import { spawnSync } from "node:child_process";
import { createJiti } from "jiti";
import { summaryFixture } from "./task-summary-fixture.mjs";
const jiti = createJiti(import.meta.url, { alias: { "@": process.cwd() } });
const { emptyTaskFilter } = await jiti.import("./task-view.ts");
const { startRpcSession } = await jiti.import("./rpc-manager.ts");
const { POST } = await jiti.import("../app/api/agent/[id]/route.ts");

test("11 main joint migration and actual SDK clone preserve 07 AI provenance, 05 views, 06 history and every old CAS/receipt", async (t) => {
  const f = await summaryFixture(), previous = process.env.PI_CODING_AGENT_DIR;
  process.env.PI_CODING_AGENT_DIR = f.agentDir;
  t.after(async () => {
    for (const w of globalThis.__piSessions?.values() ?? []) await w.shutdown();
    if (previous === undefined) delete process.env.PI_CODING_AGENT_DIR; else process.env.PI_CODING_AGENT_DIR = previous;
    await rm(f.agentDir, { recursive: true, force: true });
  });
  const generated = await f.generate(await f.snapshot());
  const ai = { action: "publish-context", id: f.task.id, operationId: randomUUID(), expectedCurrentVersionId: null, generationId: generated.generationId, content: generated.content };
  const confirmed = await f.call(ai);
  const manual = { action: "publish-context", id: f.task.id, operationId: randomUUID(), expectedCurrentVersionId: confirmed.task.sharedContext.currentVersionId, content: { ...generated.content, goal: "Later manual" } };
  const later = await f.call(manual);
  const restore = { action: "restore-context", id: f.task.id, operationId: randomUUID(), expectedCurrentVersionId: later.task.sharedContext.currentVersionId, versionId: confirmed.task.sharedContext.currentVersionId };
  await f.call(restore);
  const save = { action: "save-view", id: randomUUID(), operationId: randomUUID(), expectedViewsRevision: 0, name: "Joint copy", filter: emptyTaskFilter(), sort: "updated" };
  const saved = await f.call(save), custom = randomUUID();
  await f.call({ action: "set-columns", expectedColumnsRevision: saved.columnsRevision, columns: [...saved.columns.map(({ id, label }) => ({ id, label })), { id: custom, label: "Copy review" }] });
  const move = { action: "move", id: f.task.id, operationId: randomUUID(), expectedRevision: f.task.revision, expectedOrderRevision: saved.orderRevision, columnId: custom, position: { edge: "end" } };
  await f.call(move);
  const good = JSON.parse(await readFile(f.file));
  const legacy = structuredClone(good); legacy.version = 4; delete legacy.sessionRelations; delete legacy.sessionCopies; await writeFile(f.file, JSON.stringify(legacy));
  const script = `import {createJiti} from 'jiti'; const {taskOperation}=await createJiti(import.meta.url).import('./lib/task-operations.ts'); await taskOperation({action:'list'},{agentDir:process.argv[1]});`;
  const migrated = spawnSync(process.execPath, ["--input-type=module", "-e", script, f.agentDir], { cwd: process.cwd(), env: process.env, encoding: "utf8" });
  assert.equal(migrated.status, 0, migrated.stderr); assert.deepEqual(JSON.parse(await readFile(f.file)), good);
  await startRpcSession(f.source.getSessionId(), f.source.getSessionFile());
  const sourceBytes = await readFile(f.source.getSessionFile());
  const command = { type: "clone", leafId: f.leaf, operationId: randomUUID() };
  const post = () => POST(new Request("http://localhost/api/agent/fixture", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(command) }), { params: Promise.resolve({ id: f.source.getSessionId() }) });
  const first = await post(); assert.equal(first.status, 200); const result = await first.json();
  assert.deepEqual(await (await post()).json(), result);
  const after = JSON.parse(await readFile(f.file));
  for (const key of ["columns", "columnsRevision", "orderRevision", "viewsRevision", "savedViews"]) assert.deepEqual(after[key], good[key]);
  const beforeTask = good.tasks[0], afterTask = after.tasks[0];
  for (const key of Object.keys(beforeTask).filter((k) => !["revision", "updatedAt", "sessionIds"].includes(k))) assert.deepEqual(afterTask[key], beforeTask[key]);
  assert.deepEqual(afterTask.sharedContext.versions.map((v) => v.source.kind), ["ai", "manual", "restore"]);
  assert.equal(afterTask.revision, beforeTask.revision + 1); assert.deepEqual(afterTask.sessionIds, [f.source.getSessionId(), result.data.newSessionId]);
  const stable = await readFile(f.file);
  for (const request of [ai, manual, restore, save, move]) { await f.call(request); assert.deepEqual(await readFile(f.file), stable); }
  await assert.rejects(f.call({ action: "set-columns", expectedColumnsRevision: 0, columns: saved.columns.map(({ id, label }) => ({ id, label })) }), { code: "conflict" });
  await assert.rejects(f.call({ action: "edit", id: f.task.id, expectedRevision: beforeTask.revision, title: "stale", description: "", completionCriteria: "", priority: 1, labels: [] }), { code: "conflict" });
  assert.deepEqual(await readFile(f.source.getSessionFile()), sourceBytes);
  assert.equal(f.captures.length, 1, "copy/receipt/migration never call the summary provider again or prompt the child");
});
